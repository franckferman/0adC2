/* atoul_s: minimal decimal string → unsigned long parser.
 * Why not strtol/atol? On glibc 2.38+, atol() resolves to __isoc23_strtol in
 * the PLT, which is a recognizable import. A clean PLT is harder for automated
 * scanners to fingerprint. Hand-rolled parser = no extra imports. */
static unsigned long atoul_s(const char *s){
    unsigned long r=0;
    while(*s>='0'&&*s<='9') r=r*10+(unsigned long)(*s++-'0');
    return r;}

